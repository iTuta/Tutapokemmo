const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const inputPath = path.join(root, 'web', 'search-data.js');
const outputPath = path.join(root, 'netlify', 'functions', '_data', 'monster-names.js');

const src = fs.readFileSync(inputPath, 'utf8');
const start = src.indexOf('{');
const end = src.lastIndexOf(';');
const data = JSON.parse(src.slice(start, end === -1 ? undefined : end));

const names = {};
(data.r || []).forEach((record) => {
  const id = record[0];
  if (!(id in names)) names[id] = record[2] || String(id);
});

const output =
  '// Generated by scripts/build-swarm-names.js — do not edit manually.\n' +
  'export default ' + JSON.stringify(names) + ';\n';

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output, 'utf8');

console.log(
  outputPath + '\n' +
  Buffer.byteLength(output).toLocaleString('en-US') + ' bytes\n' +
  Object.keys(names).length + ' names'
);
